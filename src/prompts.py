"""Промпты генерации карточки товара.

SYSTEM_PROMPT      — роль и восемь жёстких правил против галлюцинаций.
OUTPUT_SCHEMA      — строгая JSON-схема вывода (вставляется в
пользовательский промпт).
build_user_prompt() — рендер входных данных в пользовательский промпт.
RETRY_PROMPT       — уточняющее сообщение для единственной повторной
попытки при невалидном ответе модели (используется генератором).

Числовые ограничения (70 / 800–1200 / 3–5) берутся из models.py, чтобы
текст промпта не разошёлся с pydantic-валидацией ответа.
"""

from __future__ import annotations

from collections.abc import Sequence

from .models import (
    SEARCH_QUERIES_MAX,
    SEARCH_QUERIES_MIN,
    SEO_DESCRIPTION_MAX_LEN,
    SEO_DESCRIPTION_MIN_LEN,
    SEO_TITLE_MAX_LEN,
    ProductInput,
)

SYSTEM_PROMPT = f"""\
Ты — ассистент контент-менеджера B2B-магазина контрольно-измерительных
приборов. По входным данным готовишь черновик карточки товара:
SEO-заголовок, SEO-описание, характеристики, поисковые запросы и
коммерческий блок.

ЖЁСТКИЕ ПРАВИЛА (нарушение любого делает ответ непригодным):
1. Используй только факты из входных данных. Запрещено выдумывать числа,
единицы, диапазоны, классы точности, интерфейсы и любые технические
характеристики.
2. Если характеристика отсутствует во входных данных — выведи её в списке
характеристик со значением «данных нет».
3. Язык вывода — русский.
4. SEO-заголовок — не более {SEO_TITLE_MAX_LEN} символов.
5. SEO-описание — строго от {SEO_DESCRIPTION_MIN_LEN} до \
{SEO_DESCRIPTION_MAX_LEN} символов: осмысленное, без воды, без
маркетинговых преувеличений о технических параметрах.
6. Поисковых запросов — от {SEARCH_QUERIES_MIN} до {SEARCH_QUERIES_MAX}.
7. Коммерческий блок — кратко: кому подходит прибор и какие задачи он
решает (для менеджера по продажам).
8. Не ссылайся на несуществующие стандарты, сертификаты, ГОСТы — только
на те, что названы во входных данных.

Ответ верни строго в формате JSON по схеме из сообщения пользователя:
без markdown-обёрток, без пояснений и любого текста вокруг JSON.
"""

OUTPUT_SCHEMA = f"""{{
  "seo_title": "строка, не более {SEO_TITLE_MAX_LEN} символов",
  "seo_description": "строка от {SEO_DESCRIPTION_MIN_LEN} до \
{SEO_DESCRIPTION_MAX_LEN} символов",
  "specs": [
    {{"name": "название характеристики",
      "value": "значение из входа или «данных нет»"}}
  ],
  "search_queries": ["от {SEARCH_QUERIES_MIN} до {SEARCH_QUERIES_MAX} \
поисковых запросов"],
  "commercial_block": "кому подходит прибор и какие задачи решает",
  "missing_fields": ["характеристики, которых нет во входных данных"]
}}"""

# {reason} подставляет генератор — краткое описание проблемы
RETRY_PROMPT = (
    "Твой предыдущий ответ не принят: {reason}\n"
    "Верни ответ ещё раз: строго валидный JSON по той же схеме, без "
    "markdown-обёрток и пояснений. Исправь указанную проблему, остальное "
    "сохрани без изменений. Все числа бери только из входных данных."
)


def build_user_prompt(
    product: ProductInput,
    missing_fields: Sequence[str] | None = None,
) -> str:
    """Рендерит входные данные в пользовательский промпт.

    missing_fields (от валидатора входа) — ожидаемые
    характеристики, которых нет во входе; модель обязана вывести каждую
    в specs со значением «данных нет».
    """
    spec_lines = "\n".join(
        f"{key}: {value}" for key, value in product.specs.items()
    )
    if not spec_lines:
        spec_lines = "(во входе нет ни одной характеристики)"
    category = (product.category or "").strip() or "данных нет"
    description = product.description.strip() or "(нет)"

    parts = [
        "Сформируй черновик карточки товара по данным ниже.",
        "",
        f"НАЗВАНИЕ: {product.name.strip()}",
        f"ПРОИЗВОДИТЕЛЬ: {product.manufacturer.strip()}",
        f"КАТЕГОРИЯ: {category}",
        "",
        "ХАРАКТЕРИСТИКИ (используй только их; отсутствующие пометь "
        "«данных нет»):",
        spec_lines,
    ]
    if missing_fields:
        listed = "; ".join(missing_fields)
        parts += [
            "",
            "ОТСУТСТВУЮЩИЕ ХАРАКТЕРИСТИКИ (обязательно выведи каждую в "
            f"specs со значением «данных нет»): {listed}",
        ]
    parts += [
        "",
        "ОПИСАНИЕ (источник фактов):",
        description,
        "",
        "Верни СТРОГО JSON по схеме:",
        OUTPUT_SCHEMA,
    ]
    return "\n".join(parts)
